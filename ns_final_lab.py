"""Calculate the degree exponent of the directed Barabási-Albert model with accelerated growth, assuming that the degree of the newly arriving
nodes increases in time as m(t) = t
Θ
"""

import numpy as np
import networkx as nx
import matplotlib.pyplot as plt
from scipy.optimize import curve_fit
from collections import Counter

# Function for power-law fitting
def power_law(x, gamma):
    return x ** (-gamma)

# Directed Barabási-Albert model with accelerated growth
def directed_ba_accelerated_growth(n, theta, m0=2):
    G = nx.DiGraph()
    # Initial small network of m0 nodes
    G.add_nodes_from(range(m0))
    for i in range(m0):
        for j in range(i):
            G.add_edge(i, j)

    # Growth with preferential attachment
    for t in range(m0, n):
        m_t = int(t**theta)  # Accelerated growth: m(t) = t^theta
        targets = _preferential_attachment(G, m_t)
        G.add_node(t)
        for target in targets:
            G.add_edge(t, target)

    return G

# Preferential attachment: choose nodes based on their in-degree
def _preferential_attachment(G, num_edges):
    degrees = np.array([G.in_degree(n) + 1 for n in G.nodes()])  # Add 1 to avoid zero probability
    probabilities = degrees / degrees.sum()
    targets = np.random.choice(G.nodes(), size=num_edges, replace=False, p=probabilities)
    return targets

# Plot degree distribution and fit power law
def plot_degree_distribution_and_fit(G, theta):
    in_degrees = [d for _, d in G.in_degree()]
    degree_count = Counter(in_degrees)
    degrees, counts = zip(*degree_count.items())

    plt.figure(figsize=(8, 6))
    plt.scatter(degrees, counts, color='blue', label='Degree Distribution')

    # Fit the degree distribution to a power-law
    popt, _ = curve_fit(power_law, degrees, counts)
    gamma = popt[0]
    print(f"Estimated Degree Exponent (gamma) for theta={theta}: {gamma:.2f}")

    # Plot fitted power-law
    fitted = power_law(np.array(degrees), gamma)
    plt.plot(degrees, fitted, color='red', linestyle='--', label=f'Fitted Power Law (gamma={gamma:.2f})')

    plt.xscale('log')
    plt.yscale('log')
    plt.xlabel('Degree (k)')
    plt.ylabel('Count')
    plt.title(f'Degree Distribution and Power-Law Fit (theta={theta})')
    plt.legend()
    plt.show()

# Main function to run the simulation and plot the results
def main():
    n = 1000  # Total number of nodes
    theta = 0.5  # Exponent controlling the accelerated growth, m(t) = t^theta

    G = directed_ba_accelerated_growth(n, theta)
    plot_degree_distribution_and_fit(G, theta)

