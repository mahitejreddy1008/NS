import numpy as np
from scipy.integrate import quad
from scipy.stats import lognorm

# 1. Power Law with Exponential Cutoff
def power_law_exponential_cutoff(k, gamma, k_c):
    return k**(-gamma) * np.exp(-k/k_c)

def moments_power_law_exponential_cutoff(gamma, k_c, k_min=1):
    # First moment: <k>
    integrand_k = lambda k: k * power_law_exponential_cutoff(k, gamma, k_c)
    avg_k, _ = quad(integrand_k, k_min, np.inf)

    # Second moment: <k^2>
    integrand_k2 = lambda k: k**2 * power_law_exponential_cutoff(k, gamma, k_c)
    avg_k2, _ = quad(integrand_k2, k_min, np.inf)

    return avg_k, avg_k2

def critical_threshold_power_law(gamma, k_c):
    avg_k, avg_k2 = moments_power_law_exponential_cutoff(gamma, k_c)
    kappa = avg_k2 / avg_k
    fc = 1 - 1 / (kappa - 1)
    return fc

# 2. Lognormal Distribution
def moments_lognormal(mu, sigma):
    # First moment: <k>
    avg_k = np.exp(mu + 0.5 * sigma**2)

    # Second moment: <k^2>
    avg_k2 = np.exp(2 * mu + 2 * sigma**2)

    return avg_k, avg_k2

def critical_threshold_lognormal(mu, sigma):
    avg_k, avg_k2 = moments_lognormal(mu, sigma)
    kappa = avg_k2 / avg_k
    fc = 1 - 1 / (kappa - 1)
    return fc

# 3. Delta Distribution (All nodes have the same degree)
def critical_threshold_delta(k_0):
    kappa = k_0
    fc = 1 - 1 / (kappa - 1)
    return fc

