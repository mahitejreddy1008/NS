# Function to generate a scale-free network using the configuration model
def generate_scale_free_network(n, degree_sequence):
    G = nx.configuration_model(degree_sequence)
    G = nx.Graph(G)  # Remove parallel edges
    G.remove_edges_from(nx.selfloop_edges(G))  # Remove self-loops
    return G

# Function to calculate the Molloy-Reed criterion
def molloy_reed_criterion(G):
    degrees = np.array([d for n, d in G.degree()])
    k1 = np.mean(degrees)
    k2 = np.mean(degrees ** 2)
    molloy_reed = k2 / k1
    return molloy_reed

# Function to calculate the critical threshold for random failures
def critical_threshold(G):
    degrees = np.array([d for n, d in G.degree()])
    k1 = np.mean(degrees)
    k2 = np.mean(degrees ** 2)

    # Critical threshold (random failures): p_c = 1 - 1 / (k2/k1 - 1)
    p_c = 1 - 1 / (k2 / k1 - 1)
    return p_c

# Function to remove nodes from the network based on the critical threshold
def remove_random_nodes(G, fraction):
    num_nodes_to_remove = int(fraction * G.number_of_nodes())
    nodes_to_remove = np.random.choice(G.nodes(), num_nodes_to_remove, replace=False)
    G.remove_nodes_from(nodes_to_remove)
    return G

# Function to check if the network is still connected (giant connected component)
def is_connected_after_removal(G):
    largest_cc = max(nx.connected_components(G), key=len)
    size_of_largest_cc = len(largest_cc)
    total_nodes = G.number_of_nodes()
    return size_of_largest_cc, total_nodes

